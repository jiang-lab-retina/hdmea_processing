def find_alignment_pairs_from_index(
    index_csv: Path = FILE_INDEX_CSV,
    h5_folder: Path = OUTPUT_DIR,
) -> List[FilePair]:
    """
    Find before/after file pairs from the CSV file index.

    Uses pair_id to link before and gaba_gly recordings that were
    validated by temporal ordering in discover_files.py.

    Args:
        index_csv: Path to file_index.csv
        h5_folder: Folder containing processed H5 files

    Returns:
        List of FilePair objects
    """
    logger = logging.getLogger(__name__)

    if not index_csv.exists():
        logger.error(f"File index not found: {index_csv}")
        return []

    df = pd.read_csv(index_csv)
    logger.info(f"Loaded file index: {len(df)} rows")

    pairs = []

    # Get unique pair_ids (excluding empty/NaN)
    pair_ids = df[df["pair_id"].notna() & (df["pair_id"] != "")]["pair_id"].unique()
    logger.info(f"Found {len(pair_ids)} unique pair IDs")

    for pair_id in sorted(pair_ids):
        pair_rows = df[df["pair_id"] == pair_id]

        before_rows = pair_rows[pair_rows["recording_type"] == "before"]
        after_rows = pair_rows[pair_rows["recording_type"] == "gaba_gly"]

        if before_rows.empty or after_rows.empty:
            logger.warning(f"Incomplete pair {pair_id}: before={len(before_rows)}, after={len(after_rows)}")
            continue

        before_row = before_rows.iloc[0]
        after_row = after_rows.iloc[0]

        # Get H5 filenames
        before_gsheet = str(before_row["gsheet_filename"])
        after_gsheet = str(after_row["gsheet_filename"])

        before_h5_name = gsheet_to_h5_filename(before_gsheet)
        after_h5_name = gsheet_to_h5_filename(after_gsheet)

        before_h5_path = h5_folder / before_h5_name
        after_h5_path = h5_folder / after_h5_name

        if not before_h5_path.exists():
            logger.warning(f"Before H5 not found: {before_h5_path}")
            continue

        if not after_h5_path.exists():
            logger.warning(f"After H5 not found: {after_h5_path}")
            continue

        before_time = extract_timestamp_from_filename(before_gsheet)
        after_time = extract_timestamp_from_filename(after_gsheet)

        if before_time is None or after_time is None:
            logger.warning(f"Could not parse timestamps for pair {pair_id}")
            continue

        chip = str(before_row.get("chip", ""))
        genotype = str(before_row.get("genotype", ""))

        pair = FilePair(
            before_file=before_gsheet,
            after_file=after_gsheet,
            before_h5=before_h5_path,
            after_h5=after_h5_path,
            chip=chip,
            genotype=genotype,
            pair_id=pair_id,
            before_time=before_time,
            after_time=after_time,
        )
        pairs.append(pair)

        logger.info(f"Found pair {pair_id} (Chip {chip}): {before_gsheet} -> {after_gsheet}")

    logger.info(f"Total valid pairs: {len(pairs)}")
    return pairs



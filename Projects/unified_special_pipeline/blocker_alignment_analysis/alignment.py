def gsheet_to_h5_filename(gsheet_filename: str) -> str:
    """
    Convert gsheet filename format to H5 filename format.

    Example: "2025.09.04.10.11.09.Rec.cmcr" -> "2025.09.04-10.11.09-Rec.h5"
    """
    # First convert to disk format (hyphens)
    disk_name = gsheet_filename_to_disk(gsheet_filename)
    # Replace .cmcr with .h5
    return disk_name.replace(".cmcr", ".h5")


def extract_timestamp_from_filename(filename: str) -> Optional[datetime]:
    """
    Extract timestamp from gsheet filename.

    Example: "2025.09.04.10.11.09.Rec.cmcr" -> datetime(2025, 9, 4, 10, 11, 9)
    """
    try:
        base = filename.replace(".cmcr", "").replace(".h5", "")
        base = base.replace("-", ".")
        parts = base.split(".")

        if len(parts) >= 6:
            year = int(parts[0])
            month = int(parts[1])
            day = int(parts[2])
            hour = int(parts[3])
            minute = int(parts[4])
            second = int(parts[5])
            return datetime(year, month, day, hour, minute, second)
    except (ValueError, IndexError):
        pass
    return None



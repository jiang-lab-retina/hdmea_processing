"""
Blocker Alignment Analysis - Before/After Unit Alignment

This module aligns units across before/after recording pairs based on:
- Coordinate proximity (row, col)
- Response signature similarity
- Waveform signature similarity

Pairing logic:
- Uses pair_id from the CSV file index (generated by discover_files.py)
- "Before" file: Condition contains play_optimization_set6_a_ipRGC_without_step()
- "After" file: Condition contains play_optimization_set6_a_ipRGC_manual()
  AND immediately follows the before file (by timestamp) AND same Chip

Cell type classification:
- ON: Increased firing 1-3s after light ON
- OFF: Increased firing 6-8s (1-3s after light OFF)
- ON_OFF: Both ON and OFF responses
- unknown: Does not meet classification thresholds
"""


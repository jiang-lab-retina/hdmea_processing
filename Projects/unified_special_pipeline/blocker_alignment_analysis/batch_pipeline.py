def load_file_index(index_csv: Path = FILE_INDEX_CSV) -> Optional[pd.DataFrame]:
    """
    Load the file index CSV generated by discover_files.py.

    Args:
        index_csv: Path to file_index.csv

    Returns:
        DataFrame with file index, or None if not found
    """
    logger = logging.getLogger(__name__)

    if not index_csv.exists():
        logger.error(
            f"File index not found: {index_csv}\n"
            f"Run discover_files.py first to generate the index."
        )
        return None

    try:
        df = pd.read_csv(index_csv)
        logger.info(f"Loaded file index: {len(df)} rows from {index_csv}")
        return df
    except Exception as e:
        logger.error(f"Failed to load file index: {e}")
        return None


def run_batch(
    index_csv: Path = FILE_INDEX_CSV,
    output_dir: Path = OUTPUT_DIR,
    label_root: Path = LABEL_ROOT,
    start_index: int = 0,
    end_index: Optional[int] = None,
    overwrite: bool = False,
    skip_existing: bool = False,
) -> Tuple[List[str], List[str], List[Tuple[str, str]]]:
    """
    Run batch processing on files from the CSV index.

    Args:
        index_csv: Path to file_index.csv
        output_dir: Output directory for HDF5 files
        label_root: Root folder for blocker-specific axon labels
        start_index: Starting index (0-based)
        end_index: Ending index (exclusive, None for all)
        overwrite: Whether to overwrite existing files
        skip_existing: Whether to skip files that already have H5 output

    Returns:
        Tuple of (successful, skipped, failed) lists
    """
    logger = logging.getLogger(__name__)

    # Create output directory
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load file index
    index_df = load_file_index(index_csv)
    if index_df is None:
        return [], [], [("file_index", "File index not found")]

    # Filter to rows where both CMCR and CMTR exist
    valid_mask = index_df["cmcr_exists"] & index_df["cmtr_exists"]
    valid_df = index_df[valid_mask].copy()
    logger.info(f"Valid recordings (both files exist): {len(valid_df)}/{len(index_df)}")

    if valid_df.empty:
        logger.warning("No valid recordings found")
        return [], [], []

    # Apply index range
    all_rows = valid_df.reset_index(drop=True)
    if end_index is not None:
        rows_to_process = all_rows.iloc[start_index:end_index]
    else:
        rows_to_process = all_rows.iloc[start_index:]

    logger.info(f"Processing {len(rows_to_process)} of {len(all_rows)} valid recordings")

    # Load playlist and gsheet data
    logger.info("Loading configuration data...")
    available_playlists = load_available_playlists()
    gsheet_df = load_gsheet_dataframe()

    if not available_playlists:
        logger.warning("No playlists loaded - all files will use basic load")

    if gsheet_df is None:
        logger.warning("Gsheet not loaded - condition lookup will fail")

    # Track results
    successful: List[str] = []
    skipped: List[str] = []
    failed: List[Tuple[str, str]] = []

    # Process each file
    start_time = time.time()

    for i, (_, row) in enumerate(rows_to_process.iterrows(), 1):
        cmcr_path = Path(row["cmcr_path"])
        cmtr_path = Path(row["cmtr_path"])
        disk_cmcr = str(row["disk_cmcr"])
        dataset_id = get_dataset_id_from_cmcr(disk_cmcr)

        logger.info(f"\n{'='*60}")
        logger.info(f"[{i}/{len(rows_to_process)}] {dataset_id}")
        logger.info(f"{'='*60}")

        try:
            # Resolve playlist from condition (using part before first comma)
            condition = str(row.get("condition", ""))
            playlist_name = None

            if condition and available_playlists:
                playlist_name = resolve_playlist(condition, available_playlists)
                if playlist_name:
                    logger.info(f"  Condition: {condition}")
                    logger.info(f"  Resolved playlist: {playlist_name}")
                else:
                    logger.info(f"  Condition: {condition} (no matching playlist)")

            # Process the recording
            success, error = process_single_recording(
                cmcr_path=cmcr_path,
                cmtr_path=cmtr_path,
                output_dir=output_dir,
                playlist_name=playlist_name,
                gsheet_df=gsheet_df,
                label_root=label_root,
                overwrite=overwrite,
            )

            if success:
                if error == "skipped":
                    logger.info(f"  Skipped - output file already exists")
                    skipped.append(dataset_id)
                else:
                    successful.append(dataset_id)
            else:
                logger.error(f"  Failed: {error}")
                failed.append((dataset_id, error or "Unknown error"))

        except Exception as e:
            logger.error(f"  Exception: {e}")
            logger.debug(traceback.format_exc())
            failed.append((dataset_id, str(e)))

    # Summary
    elapsed = time.time() - start_time

    logger.info(f"\n{'='*60}")
    logger.info("BATCH PROCESSING COMPLETE")
    logger.info(f"{'='*60}")
    logger.info(f"Total files processed: {len(rows_to_process)}")
    logger.info(f"Successful: {len(successful)}")
    logger.info(f"Skipped (already exists): {len(skipped)}")
    logger.info(f"Failed: {len(failed)}")
    logger.info(f"Time: {elapsed:.1f}s ({elapsed/60:.1f} min)")

    if failed:
        logger.info("\nFailed recordings:")
        for dataset_id, error in failed[:10]:
            logger.info(f"  - {dataset_id}: {error}")
        if len(failed) > 10:
            logger.info(f"  ... and {len(failed) - 10} more")

    return successful, skipped, failed



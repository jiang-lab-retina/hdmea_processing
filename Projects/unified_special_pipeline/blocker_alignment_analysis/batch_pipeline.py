def resolve_playlist(
    condition: Optional[str],
    available_playlists: Set[str],
) -> Optional[str]:
    """
    Resolve condition to playlist name.

    First extracts the part before the first comma from the condition,
    then strips trailing "()" and checks against available playlists.

    Example:
        "play_optimization_set6_a_ipRGC_manual(), gaba, glycine"
        -> extract: "play_optimization_set6_a_ipRGC_manual()"
        -> strip (): "play_optimization_set6_a_ipRGC_manual"
        -> check playlists

    Args:
        condition: Condition value from gsheet
        available_playlists: Set of available playlist names

    Returns:
        Playlist name if found, None otherwise
    """
    if not condition:
        return None

    # Extract part before first comma
    playlist_condition = parse_condition_for_playlist(condition)

    # Strip trailing "()" if present
    playlist_name = playlist_condition.rstrip("()")

    # Check if it's in the available playlists
    if playlist_name in available_playlists:
        return playlist_name

    return None


